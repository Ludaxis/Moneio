/**
 * Options for fetching insights
 */
export interface GetInsightsOptions {
  workspaceId: string;
  filter?: 'all' | 'unread' | 'dismissed';
  types?: InsightType[];
  severities?: InsightSeverity[];
  limit?: number;
  offset?: number;
}

