/**
 * Calculate insights summary from a list of insights
 */
export function calculateInsightsSummary(insights: Insight[]): InsightsSummary {
  const summary: InsightsSummary = {
    total: insights.length,
    unread: 0,
    bySeverity: {
      info: 0,
      warning: 0,
      alert: 0,
      positive: 0,
    },
    byType: {},
  };

  for (const insight of insights) {
    // Count unread
    if (!insight.readAt && !insight.dismissedAt) {
      summary.unread++;
    }

    // Count by severity
    summary.bySeverity[insight.severity]++;

    // Count by type
    summary.byType[insight.type] = (summary.byType[insight.type] || 0) + 1;
  }

  return summary;
}

/**
 * Check if an insight has expired
 */
export function isInsightExpired(insight: Insight): boolean {
  if (!insight.expiresAt) return false;
  return new Date() > insight.expiresAt;
}

/**
 * Get the status of an insight
 */
export function getInsightStatus(insight: Insight): InsightStatus {
  if (insight.dismissedAt) return 'dismissed';
  if (isInsightExpired(insight)) return 'expired';
  if (insight.readAt) return 'read';
  return 'new';
}
